// 문서 제목 끝의 '(8기)' 를 떼어 그래프에 그릴 라벨을 만든다.
// 8기 크루 34명이 모두 '카야(8기)' 처럼 기수를 달고 있으면 화면이 읽히지 않으므로 떼어낸다.
//
// 제목 형식이 강제되지 않아 '루나 (7기)' 처럼 공백이 끼는 경우가 있다(469건 중 11건 실측).
// 반면 조직 문서인 'BE 8기' · '백엔드 / 8기' 는 끝이 '(N기)' 가 아니라 그대로 남는다.
//
// 기수를 떼면 '루나(8기)' 와 '루나' 가 같은 라벨이 된다. 그래도 둘은 별개 문서다 —
// 제목을 고칠 수 없어 같은 사람이 문서를 두 번 만든 흔적이기도 하고, 기수가 다른 동명이인이기도 하다.
// 노드의 정체성은 라벨이 아니라 documentUuid 이므로, 같은 라벨이 둘 보이는 것은 그대로 둔다.
// 여러 기수를 함께 볼 때 생기는 혼동은 라벨에 기수를 병기해서(isMultiGeneration) 푼다.
export const GENERATION_SUFFIX_PATTERN = /\s*\(\d+기\)\s*$/;

export const toGraphLabel = (title: string) => title.replace(GENERATION_SUFFIX_PATTERN, '');
